"""用户提示: the operator's message announced by the heartbeat.

Two stages, exactly like 更新链接 (``update_core.fetch_release_info``):

1. The licence heartbeat carries the *announcement* only — the notice sequence
   number and its level (``LicenseStatus.server_notice``).  That is enough for the
   title-bar triangle to appear in the right colour on the very tick the server
   hears about it, with no extra request.
2. The message BODY is fetched later, by :func:`fetch_notice`, and only when the
   announced sequence differs from the one already shown.  A tick that sees the
   same seq does nothing, so a 5 FPS UI never turns this into a polling loop.

The newest message is kept in memory (:func:`remember` / :func:`cached`) the same
way the release link is cached: it survives a failed server round trip, so the
icon does not flicker back to hidden because one HTTP request timed out.

The sequence number is generated by the server (the notice row's primary key).
Nothing here invents, stores or compares anything else: "newer" is ``seq >`` the
seq that is currently displayed.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

import licensing
from pinned_tls import PinnedTlsError, PinnedTlsResponseError, post_json

LOG = logging.getLogger("user-notice")

INFO_PATH = "/api/v1/notice/info"
# The message is a short operator note; a device on a bad network must not keep
# a heartbeat-driven fetch alive for long.
NOTICE_TIMEOUT = 12.0

LEVEL_CRITICAL = "critical"
LEVEL_NORMAL = "normal"
LEVELS = (LEVEL_CRITICAL, LEVEL_NORMAL)


@dataclass(frozen=True)
class Notice:
    """One published 用户提示, as the client renders it."""

    seq: int
    level: str = LEVEL_NORMAL
    message: str = ""
    published_at: str = ""

    @property
    def critical(self) -> bool:
        return self.level == LEVEL_CRITICAL

    @property
    def label(self) -> str:
        return "紧急" if self.critical else "普通"


def parse_notice(value: Any) -> Optional[Notice]:
    """Build a :class:`Notice` from the server's JSON, or ``None``.

    An older server, nothing published, and a malformed payload all mean the same
    thing to the caller: there is no message to show.  A record without text is
    useless (the icon would open an empty dialog), so it is rejected here.
    """

    if not isinstance(value, dict):
        return None
    try:
        seq = int(value.get("seq"))
    except (TypeError, ValueError):
        return None
    if seq <= 0:
        return None
    message = str(value.get("message") or "").strip()
    if not message:
        return None
    level = str(value.get("level") or LEVEL_NORMAL).strip().lower()
    if level not in LEVELS:
        level = LEVEL_NORMAL
    return Notice(
        seq=seq,
        level=level,
        message=message,
        published_at=str(value.get("published_at") or ""),
    )


def fetch_notice(root: Optional[Path] = None) -> Optional[Notice]:
    """Ask the pinned activation server for the published 用户提示.

    Never raises: no local entitlement, nothing published, or an unreachable
    server all return ``None``, and every caller treats that as "keep showing
    whatever is cached" rather than as an error.
    """

    try:
        local = licensing.verify_license(root)
    except Exception:  # noqa: BLE001 - a broken local document is not a crash
        LOG.warning("notice info: the local license could not be verified", exc_info=True)
        return None
    if not local.valid or not local.license_id:
        LOG.info("notice info: no valid local license (%s)", local.code)
        return None
    try:
        payload = {
            "fingerprint": licensing.machine_fingerprint_hash(),
            "license_id": local.license_id,
        }
        answer = post_json(
            licensing.ACTIVATION_SERVER_ENDPOINT,
            INFO_PATH,
            payload,
            licensing.runtime_root() / licensing.ACTIVATION_SERVER_PIN_FILE,
            timeout=NOTICE_TIMEOUT,
            logger=LOG,
        )
    except PinnedTlsResponseError as exc:
        LOG.warning("notice info rejected status=%s code=%s", exc.status, exc.code)
        return None
    except (PinnedTlsError, ValueError, KeyError, OSError) as exc:
        LOG.warning("notice info unavailable category=%s", type(exc).__name__)
        return None
    return parse_notice((answer or {}).get("notice"))


# The displayed message.  Deliberately a plain module global: one process, one
# client, and the value is a small frozen dataclass, so no lock is needed for an
# atomic reference swap that the UI thread and a fetch thread both do.
_CACHED: Optional[Notice] = None
# The announced seq the fetch currently in flight is for, so two ticks cannot
# ask for the same message twice while the first request is still open.
_IN_FLIGHT: Optional[int] = None


def cached() -> Optional[Notice]:
    """The message currently shown, or ``None`` when there is none."""

    return _CACHED


def remember(notice: Optional[Notice]) -> None:
    """Store the message that is now displayed (``None`` clears the icon)."""

    global _CACHED
    _CACHED = notice


def announced_seq(announcement: Optional[dict[str, Any]]) -> Optional[int]:
    """The seq inside a heartbeat announcement, or ``None``."""

    if not isinstance(announcement, dict):
        return None
    try:
        seq = int(announcement.get("seq"))
    except (TypeError, ValueError):
        return None
    return seq if seq > 0 else None


def level_of(announcement: Optional[dict[str, Any]]) -> str:
    """The level inside a heartbeat announcement, normalised."""

    if not isinstance(announcement, dict):
        return LEVEL_NORMAL
    level = str(announcement.get("level") or LEVEL_NORMAL).strip().lower()
    return level if level in LEVELS else LEVEL_NORMAL


def needs_fetch(announcement: Optional[dict[str, Any]]) -> bool:
    """Whether this announcement is a message the client does not display yet.

    Comparing sequence numbers is the whole point of the server-generated id: no
    clock, no string compare, and no browser-side bookkeeping of what was read.
    """

    seq = announced_seq(announcement)
    if seq is None:
        return False
    current = _CACHED
    return current is None or seq > current.seq


def begin_fetch(announcement: Optional[dict[str, Any]]) -> Optional[int]:
    """Claim the fetch for this announcement; returns the seq to fetch or None.

    Callers run :func:`fetch_notice` off the Tk thread.  Claiming first keeps a
    100 ms UI tick from stacking requests for the same seq; :func:`end_fetch`
    releases it, and a failure simply leaves the claim free for the next tick.
    """

    global _IN_FLIGHT
    seq = announced_seq(announcement)
    if seq is None or _IN_FLIGHT == seq:
        return None
    _IN_FLIGHT = seq
    return seq


def end_fetch() -> None:
    global _IN_FLIGHT
    _IN_FLIGHT = None


def apply_fetched(notice: Optional[Notice], announcement: Optional[dict[str, Any]]) -> Optional[Notice]:
    """Store a fetched notice, falling back to the announcement's level.

    The heartbeat says the seq AND the level, so even a fetch that came back with
    nothing usable (a race with the operator unpublishing) leaves the icon in the
    announced colour instead of hiding a message that really exists.
    """

    if notice is not None:
        remember(notice)
        return notice
    seq = announced_seq(announcement)
    if seq is None:
        return _CACHED
    current = _CACHED
    if current is not None and current.seq == seq:
        return current
    # No body: show nothing rather than an empty dialog.  A later tick retries.
    return current


def reset_for_tests() -> None:
    global _CACHED, _IN_FLIGHT
    _CACHED = None
    _IN_FLIGHT = None


